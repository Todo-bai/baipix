export const ICON_NAMES = Object.keys(ICONS) as IconName[];
export type IconName = keyof typeof ICON_ROWS | 'redo' | 'down' | 'flipV' | 'mirrorX';

/** SVG path data for an icon, merging horizontal runs. */
export function iconPath(name: IconName): { d: string; size: number } {
  const rows = ICONS[name];
  let d = '';
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length;) {
      if (row[x] !== '#') {
        x++;
        continue;
      }
      let end = x;
      while (end < row.length && row[end] === '#') end++;
      d += `M${x} ${y}h${end - x}v1h-${end - x}z`;
      x = end;
    }
  });
  return { d, size: rows.length };
}
